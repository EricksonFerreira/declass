            <div>
                <div class="clause-header-title">Condições Gerais da Locação</div>
                <div class="clause-header-subtitle">
                    Cláusulas contratuais que regem a relação entre LOCADORA e LOCATÁRIO
                </div>
            </div>
        </div>
        <div class="clause-header-bar"></div>
    </div>

    <div class="clause-grid">
        <div class="clause-grid-col">
            <div class="clause-item">
                <div class="clause-num">01</div>
                <div class="clause-body">
                    <strong>Uso do veículo.</strong>
                    O LOCATÁRIO deverá utilizar o veículo de forma regular, prudente e em conformidade com a legislação de trânsito vigente, sendo vedado o uso para fins ilícitos, competições, reboque, sublocação, transporte irregular, condução por pessoa não autorizada ou qualquer finalidade diversa daquela contratada.
                </div>
            </div>
            <div class="clause-item">
                <div class="clause-num">02</div>
                <div class="clause-body">
                    <strong>Entrega e devolução.</strong>
                    O veículo deverá ser devolvido na data, hora e local contratados, no mesmo estado em que foi entregue, ressalvado o desgaste natural decorrente do uso regular. A devolução em local diverso poderá gerar taxa adicional de retorno.
                </div>
            </div>
            <div class="clause-item">
                <div class="clause-num">03</div>
                <div class="clause-body">
                    <strong>Atraso na devolução.</strong>
                    A devolução após o prazo contratado poderá gerar cobrança de diárias adicionais, taxas operacionais, diferença tarifária e demais encargos previstos nas Condições Particulares, sem prejuízo das medidas legais cabíveis.
                </div>
            </div>
            <div class="clause-item">
                <div class="clause-num">04</div>
                <div class="clause-body">
                    <strong>Multas, pedágios e infrações.</strong>
                    O LOCATÁRIO será integralmente responsável por multas, infrações de trânsito, pedágios, estacionamentos, remoções, apreensões, taxas administrativas e demais encargos ocorridos durante o período da locação, ainda que a cobrança seja recebida pela LOCADORA após a devolução do veículo.
                </div>
            </div>
            <div class="clause-item">
                <div class="clause-num">05</div>
                <div class="clause-body">
                    <strong>Danos e avarias.</strong>
                    Danos identificados na devolução e não registrados na vistoria de retirada poderão ser cobrados do LOCATÁRIO, conforme orçamento, tabela interna, avaliação técnica ou documento equivalente. O LOCATÁRIO poderá ser responsabilizado por lucros cessantes enquanto o veículo estiver em reparo.
                </div>
            </div>
            <div class="clause-item">
                <div class="clause-num">06</div>
                <div class="clause-body">
                    <strong>Combustível.</strong>
                    O veículo deverá ser devolvido com o mesmo nível de combustível informado na retirada. Havendo diferença, poderão ser cobrados o combustível faltante e a taxa de reabastecimento aplicável, conforme valores vigentes na data da devolução.
                </div>
            </div>
        </div>
        <div class="clause-grid-col">
            <div class="clause-item">
                <div class="clause-num">07</div>
                <div class="clause-body">
                    <strong>Quilometragem.</strong>
                    Quando houver limite de quilometragem contratado, o LOCATÁRIO será responsável pelo pagamento dos quilômetros excedentes, conforme valor definido nas Condições Particulares. A violação do lacre do hodômetro poderá acarretar multa contratual.
                </div>
            </div>
            <div class="clause-item">
                <div class="clause-num">08</div>
                <div class="clause-body">
                    <strong>Caução e autorização de cobrança.</strong>
                    O LOCATÁRIO autoriza a LOCADORA a realizar bloqueio, caução, pré-autorização ou retenção de valores em seu cartão de crédito ou conta bancária, bem como a efetuar cobranças referentes a diárias, taxas, multas, avarias, combustível, limpeza, quilometragem excedente, franquias, coparticipações e demais encargos previstos neste contrato.
                </div>
            </div>
            <div class="clause-item">
                <div class="clause-num">09</div>
                <div class="clause-body">
                    <strong>Acidente, roubo, furto ou pane.</strong>
                    O LOCATÁRIO deverá comunicar imediatamente a LOCADORA em caso de acidente, roubo, furto, pane, apreensão ou qualquer ocorrência envolvendo o veículo, apresentando boletim de ocorrência quando aplicável. O não cumprimento poderá acarretar a perda das proteções contratadas.
                </div>
            </div>
            <div class="clause-item">
                <div class="clause-num">10</div>
                <div class="clause-body">
                    <strong>Proteções e franquias.</strong>
                    As proteções contratadas, franquias, coparticipações e limites de cobertura serão aqueles descritos nas Condições Particulares. A proteção poderá não se aplicar em caso de uso indevido, dolo, culpa grave, infração contratual ou condução por pessoa não autorizada.
                </div>
            </div>
            <div class="clause-item">
                <div class="clause-num">11</div>
                <div class="clause-body">
                    <strong>Limpeza e conservação.</strong>
                    O veículo deverá ser devolvido em condições normais de limpeza e conservação. Sujeira excessiva, mau uso, odores, manchas, danos internos ou necessidade de higienização especial poderão gerar cobrança adicional de taxa de limpeza.
                </div>
            </div>
            <div class="clause-item">
                <div class="clause-num">12</div>
                <div class="clause-body">
                    <strong>Declaração final.</strong>
                    Ao assinar este contrato, o LOCATÁRIO declara ter lido, compreendido e aceitado as Condições Particulares, as Condições Gerais, o laudo de vistoria, as regras de cobrança, as políticas de uso do veículo e demais documentos vinculados à locação, comprometendo-se a cumpri-los integralmente.
                </div>
            </div>
        </div>
    </div>

