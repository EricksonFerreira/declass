<div class="section-title">Condições Gerais da Locação</div>
<div class="clause-box">
    <p>
        <strong>1. Uso do veículo.</strong>
        O LOCATÁRIO deverá utilizar o veículo de forma regular, prudente e em conformidade com a legislação de trânsito vigente,
        sendo vedado o uso para fins ilícitos, competições, reboque, sublocação, transporte irregular, condução por pessoa não autorizada
        ou qualquer finalidade diversa daquela contratada.
    </p>
    <p>
        <strong>2. Entrega e devolução.</strong>
        O veículo deverá ser devolvido na data, hora e local contratados, no mesmo estado em que foi entregue,
        ressalvado o desgaste natural decorrente do uso regular.
    </p>
    <p>
        <strong>3. Atraso na devolução.</strong>
        A devolução após o prazo contratado poderá gerar cobrança de diárias adicionais, taxas operacionais,
        diferença tarifária e demais encargos previstos nas Condições Particulares.
    </p>
    <p>
        <strong>4. Multas, pedágios e infrações.</strong>
        O LOCATÁRIO será integralmente responsável por multas, infrações de trânsito, pedágios, estacionamentos,
        remoções, apreensões, taxas administrativas e demais encargos ocorridos durante o período da locação,
        ainda que a cobrança seja recebida pela LOCADORA após a devolução do veículo.
    </p>
    <p>
        <strong>5. Danos e avarias.</strong>
        Danos identificados na devolução e não registrados na vistoria de retirada poderão ser cobrados do LOCATÁRIO,
        conforme orçamento, tabela interna, avaliação técnica ou documento equivalente.
    </p>
    <p>
        <strong>6. Combustível.</strong>
        O veículo deverá ser devolvido com o mesmo nível de combustível informado na retirada.
        Havendo diferença, poderão ser cobrados o combustível faltante e a taxa de reabastecimento aplicável.
    </p>
    <p>
        <strong>7. Quilometragem.</strong>
        Quando houver limite de quilometragem, o LOCATÁRIO será responsável pelo pagamento dos quilômetros excedentes,
        conforme valor definido nas Condições Particulares.
    </p>
    <p>
        <strong>8. Caução e autorização de cobrança.</strong>
        O LOCATÁRIO autoriza a LOCADORA a realizar bloqueio caução, pré-autorização ou retenção de valores,
        bem como a efetuar cobranças referentes a diárias, taxas, multas, avarias, combustível, limpeza,
        quilometragem excedente, franquias, coparticipações e demais encargos previstos neste contrato.
    </p>
    <p>
        <strong>9. Acidente, roubo, furto ou pane.</strong>
        O LOCATÁRIO deverá comunicar imediatamente a LOCADORA em caso de acidente, roubo, furto, pane,
        apreensão ou qualquer ocorrência envolvendo o veículo, apresentando boletim de ocorrência quando aplicável.
    </p>
    <p>
        <strong>10. Proteções e franquias.</strong>
        As proteções contratadas, franquias, coparticipações e limites de cobertura serão aqueles descritos nas Condições Particulares.
        A proteção poderá não se aplicar em caso de uso indevido, dolo, culpa grave, infração contratual ou condução por pessoa não autorizada.
    </p>
    <p>
        <strong>11. Limpeza e conservação.</strong>
        O veículo deverá ser devolvido em condições normais de limpeza e conservação.
        Sujeira excessiva, mau uso, odores, manchas, danos internos ou necessidade de higienização especial poderão gerar cobrança adicional.
    </p>
    <p>
        <strong>12. Declaração final.</strong>
        Ao assinar este contrato, o LOCATÁRIO declara ter lido, compreendido e aceitado as Condições Particulares,
        as Condições Gerais, o laudo de vistoria, as regras de cobrança, as políticas de uso do veículo e demais documentos vinculados à locação.
    </p>
</div>
